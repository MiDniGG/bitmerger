let LANG = (() => {
  try { const s = localStorage.getItem("bitmerger.lang"); if (s === "de" || s === "en") return s; } catch (e) {}
  return (navigator.language || "en").toLowerCase().startsWith("de") ? "de" : "en";
})();

// A key with "_one" is used instead when the count {n} (or the first number given) is 1.
function t(key, vars) {
  const n = vars && (vars.n ?? vars.ok ?? vars.a);
  if (n === 1 || n === "1") {
    const one = (TEXTS[LANG] && TEXTS[LANG][key + "_one"]) ?? TEXTS.en[key + "_one"];
    if (one !== undefined) key = key + "_one";
  }
  let s = (TEXTS[LANG] && TEXTS[LANG][key]) ?? TEXTS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(String(v));
  return s;
}

function setLang(l) {
  LANG = l;
  try { localStorage.setItem("bitmerger.lang", l); } catch (e) {}
  document.documentElement.lang = l;
}
